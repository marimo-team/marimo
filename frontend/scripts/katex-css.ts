import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { generate, lexer, List, parse, type CssNode } from "css-tree";
import { format } from "oxfmt";
import postcss, { type Rule } from "postcss";
import stylelint from "stylelint";

// The published types omit this lexer helper, which identifies matched
// shorthand components without reimplementing CSS font grammar.
declare module "css-tree" {
  interface LexerMatchResult {
    isProperty(node: CssNode, property: string): boolean;
  }
}

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
export const stylesheetPath = path.resolve(
  scriptDirectory,
  "../src/css/katex.min.css",
);
const require = createRequire(import.meta.url);

export function readUpstreamCss(): Promise<string> {
  return readFile(require.resolve("katex/dist/katex.min.css"), "utf8");
}

const header = `/*
 * Generated from the installed katex/dist/katex.min.css.
 * Run \`pnpm sync-katex-css\` from the repository root or frontend to regenerate.
 * Do not edit this file directly; update scripts/katex-css.ts for local overrides.
 *
 * Documented marimo overrides:
 * - Remove @font-face: font declarations live in katex-fonts.css.
 * - Preserve em units so scripts, rules, and spacing scale with surrounding math.
 * - Replace .katex's font shorthand with its font-family, font-size: 110%,
 *   font-style: normal, and line-height: inherit to follow surrounding text size
 *   and keep math upright in blockquotes.
 * - Right-align display equation tags.
 * - Reset equation counters on each display block as well as body.
 * - Preserve duplicate SVG rules in their upstream order and scope, with a
 *   targeted stylelint exemption so their cascade remains intact.
 * Formatting and syntax normalization use oxfmt and stylelint; adjacent exact
 * duplicate declarations left by vendor-prefix normalization are removed.
 */

/* stylelint-disable unit-allowed-list -- KaTeX sizes are relative to the math. */

`;

async function formatCss(css: string): Promise<string> {
  const result = await format("katex.min.css", css);
  if (result.errors.length > 0) {
    throw new Error(
      `Cannot format KaTeX CSS: ${JSON.stringify(result.errors)}`,
    );
  }
  return result.code;
}

function parseFontFamily(shorthand: string): string {
  try {
    const value = parse(shorthand, { context: "value" });
    const match = lexer.matchProperty("font", value);
    if (match.error || value.type !== "Value") {
      throw new Error("Invalid font shorthand");
    }
    const nodes = value.children.toArray();
    const familyStart = nodes.findIndex((node) =>
      match.isProperty(node, "font-family"),
    );
    // System fonts, CSS-wide keywords, and unresolved variables cannot supply
    // a concrete family list to preserve when replacing the shorthand.
    if (familyStart === -1) {
      throw new Error("Font shorthand has no explicit family list");
    }
    value.children = new List<CssNode>().fromArray(nodes.slice(familyStart));
    return generate(value);
  } catch (error) {
    throw new Error(
      "Cannot safely parse the upstream KaTeX font shorthand; review the font override in frontend/scripts/katex-css.ts.",
      { cause: error },
    );
  }
}

export async function generateKatexCss(upstream: string): Promise<string> {
  const root = postcss.parse(await formatCss(upstream));
  root.walkAtRules("font-face", (rule) => {
    rule.remove();
  });

  function findRule(selector: string): Rule {
    const rules: Rule[] = [];
    root.walkRules(selector, (rule) => {
      rules.push(rule);
    });
    if (rules.length !== 1) {
      throw new Error(
        `Expected one upstream ${selector} rule; review KaTeX overrides in frontend/scripts/katex-css.ts.`,
      );
    }
    return rules[0];
  }

  const math = findRule(".katex");
  const font = math.nodes.find(
    (node) => node.type === "decl" && node.prop === "font",
  );
  if (!font || font.type !== "decl") {
    throw new Error(
      "Upstream KaTeX font shorthand changed; review the font override in frontend/scripts/katex-css.ts.",
    );
  }
  font.replaceWith(
    postcss.decl({
      prop: "font-family",
      value: parseFontFamily(font.value),
    }),
    postcss.decl({ prop: "font-size", value: "110%" }),
    postcss.decl({ prop: "font-style", value: "normal" }),
  );

  function setOverride(rule: Rule, property: string, value: string): void {
    const [first, ...duplicates] = rule.nodes.filter(
      (node) => node.type === "decl" && node.prop === property,
    );
    const declaration = postcss.decl({ prop: property, value });
    if (first) {
      first.replaceWith(declaration);
    } else {
      rule.append(declaration);
    }
    for (const duplicate of duplicates) {
      duplicate.remove();
    }
  }

  setOverride(math, "line-height", "inherit");
  const tag = findRule(".katex-display > .katex > .katex-html > .katex-tag");
  setOverride(tag, "text-align", "right");

  const counters = findRule("body");
  const counterDeclarations = counters.nodes.filter(
    (node) => node.type === "decl" && node.prop === "counter-reset",
  );
  if (
    counterDeclarations.length !== 1 ||
    counterDeclarations[0].value !== "katexEqnNo mmlEqnNo"
  ) {
    throw new Error(
      "Upstream equation counters changed; review overrides in frontend/scripts/katex-css.ts.",
    );
  }
  counters.selector = "body, .katex-display";

  const svgScopes = new Set<NonNullable<Rule["parent"]>>();
  root.walkRules(".katex svg", (rule) => {
    const parent = rule.parent;
    if (!parent) {
      return;
    }
    if (svgScopes.has(parent)) {
      // Moving declarations across intervening rules or scopes can change the
      // cascade. Exempt only this duplicate rule instead of merging it.
      rule.before(
        postcss.comment({
          text: "stylelint-disable no-duplicate-selectors -- Preserve the upstream SVG cascade.",
        }),
      );
      rule.after(
        postcss.comment({ text: "stylelint-enable no-duplicate-selectors" }),
      );
    }
    svgScopes.add(parent);
  });

  const formatted = await formatCss(header + root.toString());
  const linted = await stylelint.lint({
    code: formatted,
    codeFilename: stylesheetPath,
    configFile: path.resolve(scriptDirectory, "../.stylelintrc.cjs"),
    fix: true,
  });
  if (linted.errored) {
    throw new Error(
      `Generated KaTeX CSS failed stylelint: ${JSON.stringify(linted.results)}`,
    );
  }
  // Vendor prefixes can normalize to identical declarations during stylelint's
  // fixes. Remove only adjacent exact duplicates; retain fallback ordering.
  const normalized = postcss.parse(linted.code ?? formatted);
  normalized.walkDecls((decl) => {
    const previous = decl.prev();
    if (
      previous?.type === "decl" &&
      previous.prop === decl.prop &&
      previous.value === decl.value &&
      previous.important === decl.important
    ) {
      decl.remove();
    }
  });
  return formatCss(normalized.toString());
}

export async function checkKatexCss(
  upstream: string,
  local: string,
): Promise<void> {
  if (local !== (await generateKatexCss(upstream))) {
    throw new Error(
      "KaTeX stylesheet drift detected. Run `pnpm sync-katex-css` from the repository root, review the CSS diff, then run `pnpm --dir frontend test src/css/katex-css.test.ts`. Change documented overrides in frontend/scripts/katex-css.ts if needed; do not hand-edit katex.min.css.",
    );
  }
}
